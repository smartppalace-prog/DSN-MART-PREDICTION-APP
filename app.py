import streamlit as st
import pandas as pd
import numpy as np
import pickle
from catboost import CatBoostRegressor

#PAGE CONFIGURATION
st.set_page_config(page_title="DSN Mart Sales Predictor",
                   page_icon="🛒",layout="centered")

#LOAD MODEL AND METADATA
@st.cache_resource
def load_model():
    model = CatBoostRegressor()
    model.load_model("catboost_dsn_mart_sales.cbm")
    return model

@st.cache_data
def load_metadata():
    with open("deployment_metadata.pkl", "rb") as f:
        return pickle.load(f)

model = load_model()
metadata = load_metadata()
product_weight_map = metadata["product_weight_map"]
store_size_map = metadata["store_size_map"]
features = metadata["features"]

#APP HEADER
st.title("🛒 DSN Mart Sales Predictor")
st.write("Predict expected product sales using a machine learning model" 
         "trained on DSN Mart historical sales data.")

#INPUTS
st.subheader("Product Information")
product_code = st.selectbox(
    "Product Code", sorted(product_weight_map.keys()))

product_weight = product_weight_map.get(product_code)
if product_weight is None:
    product_weight = st.number_input(
        "Product Weight (kg)", min_value=0.01, value=1.0)
else:
    st.info(f"Product weight: {product_weight:.2f} kg")

fat_content = st.selectbox("Fat Content", ["Low Fat", "Regular"])

shelf_visibility = st.slider("Shelf Visibility", 0.00, 0.35, 0.10, 0.01)

product_category = st.text_input(
    "Product Category", value="food").strip().lower()

product_price = st.number_input(
    "Product Price (₦)", min_value=0.01, value=100.0, step=10.0)

st.subheader("Store Information")
store_code = st.selectbox("Store Code", sorted(store_size_map.keys()))

store_age_years = st.number_input(
    "Store Age (Years)", min_value=0, max_value=100, value=10)

store_size = store_size_map.get(store_code)
if store_size is None:
    store_size = st.selectbox(
        "Store Size", ["Small", "Medium", "Large", "Missing"])
else:
    st.info(f"Store size: {store_size}")

store_location_tier = st.selectbox(
    "Store Location Tier", ["Tier 1", "Tier 2", "Tier 3"])

store_format = st.selectbox(
    "Store Format",["Corner Shop","Standard Supermarket",
                     "Superstore","Flagship Hypermarket"])

#PREDICTION
if st.button("Predict Total Sales", type="primary"):
    #FEATURE ENGINEERING
    price_per_kg = product_price / product_weight
    log_price = np.log1p(product_price)

    store_category = store_code + "_" + product_category

    format_category = store_format + "_" + product_category
    
    store_location_format = store_location_tier + "_" + store_format

    #CREATE INPUT ROW
    input_data = pd.DataFrame([{
        "product_code": product_code,
        "product_weight_kg": product_weight,
        "fat_content": fat_content,
        "shelf_visibility": shelf_visibility,
        "product_category": product_category,
        "product_price": product_price,
        "store_code": store_code,
        "store_age_years": store_age_years,
        "store_size": store_size,
        "store_location_tier": store_location_tier,
        "store_format": store_format,
        "price_per_kg": price_per_kg,
        "log_price": log_price,
        "store_category": store_category,
        "format_category": format_category,
        "store_location_format": store_location_format
    }])

    #ENSURE EXACT TRAINING FEATURE ORDER
    input_data = input_data[features]

    #CONVERT CATEGORICAL COLUMNS TO STRINGS
    cat_cols = input_data.select_dtypes(include="object").columns.tolist()
    for col in cat_cols:
        input_data[col] = input_data[col].fillna("Missing").astype(str)

    #PREDICTION
    prediction = max(0, model.predict(input_data)[0])

    #PREVENT NEGATIVE SALES
    st.success(f"### Predicted Total Sales: ₦{prediction:,.2f}")
    st.caption(
        "Prediction generated by the final CatBoost regression model.")